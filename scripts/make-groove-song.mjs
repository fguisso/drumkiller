/** Generate an importable study using the game's MIDI writer and WAV encoder.
 * No audio device, MIDI port, network service or external Groove dependency is used.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import JSZip from 'jszip';

const root = fileURLToPath(new URL('../', import.meta.url));
const input = path.resolve(process.argv[2] ?? path.join(root, 'studies/stand-by-me-segunda-parte.json'));
const study = JSON.parse(await fs.readFile(input, 'utf8'));
if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(study.id)) throw new Error('Invalid study id');
if (!Number.isInteger(study.countInBars) || study.countInBars < 1 || study.countInBars > 8) throw new Error('Invalid count-in');
const output = path.resolve(process.argv[3] ?? path.join(root, 'public/songs', study.id));
// Existing local packages may contain personal audio. Never overwrite one silently.
const marker = path.join(output, '.generated-groove-study');
try {
  const files = await fs.readdir(output);
  if (files.length && !files.includes('.generated-groove-study')) throw new Error(`Refusing to overwrite existing folder: ${output}`);
} catch (err) { if (err.code !== 'ENOENT') throw err; }

const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom' });
try {
  const { chartFromGroove } = await server.ssrLoadModule('/src/song/groove.ts');
  const { chartToMidi } = await server.ssrLoadModule('/src/midi/chart.ts');
  const { writeMidi } = await server.ssrLoadModule('/src/midi/smf.ts');
  const { encodeWav } = await server.ssrLoadModule('/src/audio/wav.ts');
  const { bars, seconds, chart } = chartFromGroove(study.groove);
  const offset = study.countInBars * 4 * 60 / study.groove.tempo;
  const length = offset + chart.duration;
  const sampleRate = 22050;
  const pcm = new Float32Array(Math.ceil(length * sampleRate));
  // Quiet synthesized quarter-note clicks. Accent beat 1, stop after the last bar.
  for (let beat = 0; beat < (bars + study.countInBars) * 4; beat++) {
    const start = Math.round(beat * 60 / study.groove.tempo * sampleRate);
    const freq = beat % 4 === 0 ? 1200 : 850;
    for (let i = 0; i < sampleRate * 0.025; i++) {
      pcm[start + i] += 0.18 * Math.sin(2 * Math.PI * freq * i / sampleRate) * Math.exp(-i / (sampleRate * 0.004));
    }
  }
  const meta = { format: 1, id: study.id, title: study.title,
    artist: study.artist, album: 'Estudo com clique sintetizado', charter: 'fguisso',
    bpm: study.groove.tempo, offset, length, audio: 'click.wav', charts: { expert: 'expert.mid' }, accent: '#49c5b6' };
  const report = { source: study.source, bars, editorBlocks: study.groove.measures,
    repeats: study.groove.repeats, notes: chart.notes.length, bpm: study.groove.tempo,
    countInBars: study.countInBars, chartSeconds: seconds, offset, length,
    backing: 'Generated click only. No recording of the song.',
    alignment: 'Standalone second-part study. Recording offset and coda are not confirmed.',
    order: study.order };
  const files = {
    'song.json': JSON.stringify(meta, null, 2) + '\n',
    'expert.mid': writeMidi(chartToMidi(chart, { trackName: study.title })),
    'click.wav': new Uint8Array(encodeWav([pcm], sampleRate)),
    'study.json': JSON.stringify(report, null, 2) + '\n',
    'LEIA-ME.txt': `${study.title}: ${bars} compassos a ${study.groove.tempo} BPM.\n`
      + `${study.countInBars} compassos de clique antes da primeira nota. Expert preserva todas as notas.\n`
      + 'Outras dificuldades sao simplificadas automaticamente pelo jogo.\n'
      + 'Este pacote usa somente clique sintetizado, sem a gravacao da musica.\n'
      + 'A coda e o alinhamento com a gravacao continuam pendentes.\n',
  };
  await fs.mkdir(output, { recursive: true });
  await fs.writeFile(marker, 'Generated by scripts/make-groove-song.mjs\n');
  const zip = new JSZip();
  for (const [name, data] of Object.entries(files)) {
    await fs.writeFile(path.join(output, name), data);
    zip.file(`${study.id}/${name}`, data, { date: new Date('2026-11-07T00:00:00Z') });
  }
  const zipPath = process.argv[3] ? `${output}.zip` : path.join(root, 'local', `${study.id}.zip`);
  await fs.mkdir(path.dirname(zipPath), { recursive: true });
  await fs.writeFile(zipPath, await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' }));
  console.log(JSON.stringify({ output, zipPath, bars, notes: chart.notes.length,
    bpm: study.groove.tempo, countInBars: study.countInBars, chartSeconds: seconds }, null, 2));
} finally {
  await server.close();
}
